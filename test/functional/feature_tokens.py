    def reissue_prec_change(self):
        self.log.info("Testing precision change on reissue...")
        n0 = self.nodes[0]
        self.mine_with_mocktime(n0, 10)

        token_name = "PREC_CHANGES"
        address = n0.getnewaddress()

        n0.issue(token_name, 10, 0, True, False, "", "")
        self.mine_with_mocktime(n0, 1)
        assert_equal(0, n0.listtokens("*", True)[token_name]["units"])

        for i in range(0, 6):
            n0.reissue(token_name, 10.0 ** (-i), True, address, "", i + 1)
            self.mine_with_mocktime(n0, 1)
            assert_equal(i + 1, n0.listtokens("*", True)[token_name]["units"])
            assert_raises_rpc_error(
                -25,
                "Error: Unable to reissue token: unit must be larger than current unit selection",
                n0.reissue,
                token_name,
                10.0 ** (-i),
                True,
                address,
                "",
                i,
            )

        n0.reissue(token_name, 0.000001, True, address)
        self.mine_with_mocktime(n0, 1)
        assert_equal("11.111111", n0.listtokens("*", True)[token_name]["amount"])

    def token_data_checks(self):
        self.log.info("Checking gettokendata for each token type...")
        n0, n1 = self.nodes[0], self.nodes[1]
        self.mine_with_mocktime(n0, 10)

        n0.issue(token_name="GTD", qty=1000, units=2)
        self.mine_with_mocktime(n0, 1)
        n0.issue(token_name="GTD/SUB", qty=5, units=1)
        n0.issue(token_name="GTD#U1")
        self.mine_with_mocktime(n0, 1)

        gtd = n0.gettokendata("GTD")
        assert_equal(gtd, {"name": "GTD", "token_type": "YA-token", "amount": "1000.00",
                           "units": 2, "reissuable": 1, "has_ipfs": 0})
        assert_equal(n0.gettokendata("GTD/SUB"), {"name": "GTD/SUB", "token_type": "Sub-token",
                                                  "amount": "5.0", "units": 1, "reissuable": 1,
                                                  "has_ipfs": 0})
        assert_equal(n0.gettokendata("GTD#U1"), {"name": "GTD#U1", "token_type": "Unique-token",
                                                 "amount": "1", "units": 0, "reissuable": 0,
                                                 "has_ipfs": 0})
        # Owner tokens have no metadata of their own.
        assert_equal(n0.gettokendata("GTD!"), None)
        assert_equal(n0.gettokendata("MISSING"), None)
        # The other token RPCs capitalize the name (listtokens finds "gtd").
        assert_equal(list(n0.listtokens("gtd")), ["GTD"])
        lower = n0.gettokendata("gtd")
        self.known_failure(CASE_SENSITIVE, lambda: assert_equal(lower, gtd), "not(None == ")

        self.log.info("Checking invalid change addresses...")
        a1 = n1.getnewaddress()
        assert_raises_rpc_error(-8, "YAC change address must be a valid address. Invalid address: foo",
                                n0.transfer, "GTD", 1, a1, "foo")
        assert_raises_rpc_error(-8, "Token change address must be a valid address. Invalid address: foo",
                                n0.transfer, "GTD", 1, a1, "", "foo")
        assert_raises_rpc_error(-5, "Invalid Change Address: Invalid Yacoin address: foo",
                                n0.issue, "GTDX", 1, 0, True, False, "", "", "foo")
        # big_test made TEST_YATOKEN non-reissuable.
        assert_raises_rpc_error(-25, "Unable to reissue token: reissuable is set to false",
                                n0.reissue, "TEST_YATOKEN", 1)

    def transferfromaddress_checks(self):
        self.log.info("Checking transferfromaddress()...")
        n0, n1 = self.nodes[0], self.nodes[1]
        self.mine_with_mocktime(n0, 10)
        aT = n0.getnewaddress()
        a1, a1b, a1c = n1.getnewaddress(), n1.getnewaddress(), n1.getnewaddress()

        n0.issue(token_name="TFA", qty=1000, units=2, reissuable=True, has_ipfs=False, to_address=aT)
        self.mine_with_mocktime(n0, 1)

        n0.transferfromaddress("TFA", aT, 100, a1)
        self.mine_with_mocktime(n0, 1)
        assert_equal(n1.listmytokens("TFA"), {"TFA": "100.00"})
        holders = n0.listaddressesbytoken("TFA")
        assert_equal(holders[a1], "100.00")
        assert_equal(sorted(holders.values()), ["100.00", "900.00"])
        assert aT not in holders

        assert_raises_rpc_error(-8, "Wallet doesn't own the token_name: NOTMINE",
                                n0.transferfromaddress, "NOTMINE", aT, 1, a1)
        assert_raises_rpc_error(-8, "No token outpoints are selected from the given address, failed to create the transaction",
                                n0.transferfromaddress, "TFA", aT, 1, a1)
        assert_raises_rpc_error(-8, "From address must be valid addresses. Invalid address: foo",
                                n0.transferfromaddress, "TFA", "foo", 1, a1)
        change = [a for a in holders if a != a1][0]
        assert_raises_rpc_error(-25, "Insufficient token funds",
                                n0.transferfromaddress, "TFA", change, 5000, a1)

        # transfer sends the token change to token_change_address.
        yc, tc = n0.getnewaddress(), n0.getnewaddress()
        n0.transfer("TFA", 50, a1b, yc, tc)
        self.mine_with_mocktime(n0, 1)
        assert_equal(n0.listtokenbalancesbyaddress(tc), {"TFA": "850.00"})

        yc2, tc2 = n0.getnewaddress(), n0.getnewaddress()
        n0.transferfromaddress("TFA", tc, 10, a1c, yc2, tc2)
        self.mine_with_mocktime(n0, 1)
        at_tc2 = n0.listtokenbalancesbyaddress(tc2)
        holders = n0.listaddressesbytoken("TFA")
        assert_equal(sorted(holders.values()), ["10.00", "100.00", "50.00", "840.00"])
        assert tc not in holders
        self.known_failure(CHANGE_IGNORED, lambda: assert_equal(at_tc2, {"TFA": "840.00"}), "not({} == ")

    def paging_checks(self):
        self.log.info("Checking count, start, onlytotal and confs...")
        n0 = self.nodes[0]
        self.mine_with_mocktime(n0, 10)
        ap = n0.getnewaddress()
        for name in ["PAGEA", "PAGEB", "PAGEC"]:
            n0.issue(token_name=name, qty=1, units=0, reissuable=True, has_ipfs=False, to_address=ap)
        self.mine_with_mocktime(n0, 1)

        assert_equal(n0.listmytokens("PAGE*", False, 10, 0, 2), {})
        self.mine_with_mocktime(n0, 1)
        all_pages = {"PAGEA": "1", "PAGEA!": "1", "PAGEB": "1", "PAGEB!": "1", "PAGEC": "1", "PAGEC!": "1"}
        assert_equal(n0.listmytokens("PAGE*", False, 10, 0, 2), all_pages)
        assert_equal(n0.listmytokens("PAGE*", False, 2, 1), {"PAGEA!": "1", "PAGEB": "1"})
        assert_equal(n0.listmytokens("PAGE*", False, 10, -1), {"PAGEC!": "1"})
        assert_raises_rpc_error(-8, "Invalid token name.", n0.listmytokens, "bad-name")

        assert_equal(n0.listtokens("PAGE*", False, 2, 1), ["PAGEB", "PAGEC"])
        assert_equal(n0.listtokens("PAGE*", False, 10, -2), ["PAGEB", "PAGEC"])

        # The token DB sorts names by length first, so the owner tokens come last.
        assert_equal(n0.listtokenbalancesbyaddress(ap), all_pages)
        assert_equal(n0.listtokenbalancesbyaddress(ap, True), 6)
        assert_equal(n0.listtokenbalancesbyaddress(ap, False, 2, 2), {"PAGEC": "1", "PAGEA!": "1"})
        assert_raises_rpc_error(-5, "Invalid Yacoin address: foo", n0.listtokenbalancesbyaddress, "foo")
        last_two = n0.listtokenbalancesbyaddress(ap, False, 2, -2)
        self.known_failure(NEGATIVE_START, lambda: assert_equal(last_two, {"PAGEB!": "1", "PAGEC!": "1"}), "not({} == ")

        # TFA has four holders after transferfromaddress_checks.
        holders = n0.listaddressesbytoken("TFA")
        ordered = sorted(holders)
        assert_equal(len(ordered), 4)
        assert_equal(n0.listaddressesbytoken("TFA", True), 4)
        assert_equal(n0.listaddressesbytoken("TFA", False, 1, 1), {ordered[1]: holders[ordered[1]]})
        last = n0.listaddressesbytoken("TFA", False, 5, -1)
        self.known_failure(NEGATIVE_START, lambda: assert_equal(last, {ordered[3]: holders[ordered[3]]}), "not({} == ")

        for rpc, args in [(n0.listmytokens, ["*", False]), (n0.listtokens, ["*", False]),
                          (n0.listaddressesbytoken, ["TFA", False]),
                          (n0.listtokenbalancesbyaddress, [ap, False])]:
            assert_raises_rpc_error(-8, "count must be greater than 1.", rpc, *args, 0)

    def cidv1_checks(self):
        self.log.info("Checking CIDv1 IPFS hashes...")
        n0 = self.nodes[0]
        self.mine_with_mocktime(n0, 10)
        a0 = n0.getnewaddress()

        # Both forms encode the same multihash, so either one gives the same pair.
        n0.issue(token_name="CIDONE", qty=10, units=0, reissuable=True, has_ipfs=True, ipfs_hash=IPFS1_V1)
        self.mine_with_mocktime(n0, 1)
        cidone = {"name": "CIDONE", "token_type": "YA-token", "amount": "10", "units": 0, "reissuable": 1,
                  "has_ipfs": 1, "ipfs_hash_cidv0": IPFS1, "ipfs_hash_cidv1": IPFS1_V1}
        assert_equal(n0.gettokendata("CIDONE"), cidone)
        listed = n0.listtokens("CIDONE", True)["CIDONE"]
        assert_equal((listed["ipfs_hash_cidv0"], listed["ipfs_hash_cidv1"]), (IPFS1, IPFS1_V1))

        # Raw codec instead of dag-pb, and a lone "b".
        assert_raises_rpc_error(-32602, INVALID_CIDV1, n0.issue, "CIDBAD", 10, 0, True, True,
                                IPFS1_V1.replace("bafybei", "bafkrei"))
        assert_raises_rpc_error(-32602, INVALID_CIDV1, n0.issue, "CIDBAD", 10, 0, True, True, "b")
        # "0" is not a base58 character.
        assert_raises_rpc_error(-32602, INVALID_CIDV0, n0.issue, "CIDBAD", 10, 0, True, True, IPFS1[:-1] + "0")
        assert_raises_rpc_error(-8, "Invalid parameter: ipfs_hash must be 46 characters",
                                n0.issue, "CIDBAD", 10, 0, True, True)

        n0.reissue("CIDONE", 1, True, a0, "", -1, IPFS2_V1)
        self.mine_with_mocktime(n0, 1)
        cidone.update({"amount": "11", "ipfs_hash_cidv0": IPFS2, "ipfs_hash_cidv1": IPFS2_V1})
        assert_equal(n0.gettokendata("CIDONE"), cidone)

        # An explicit empty new_ipfs (the documented default) is rejected
        # (rX9HGVUZ item 4). Once fixed, check that the reissue keeps the IPFS
        # pair after it is mined.
        assert_raises_rpc_error(-32602, INVALID_IPFS, n0.reissue, "CIDONE", 1, True, a0, "", -1, "")

        self.restart_node(0)
        connect_nodes(n0, 1)
        assert_equal(n0.gettokendata("CIDONE"), cidone)

