        self.log.info("Checking the token RPCs before activation at block 10")
        n0 = self.nodes[0]
        self.set_mocktime(TIME_GENESIS_BLOCK)

        not_active = "THIS COMMAND IS NOT YET ACTIVE"
        assert_raises_rpc_error(-1, not_active, n0.issue, "EARLY")
        assert_raises_rpc_error(-1, not_active, n0.gettokendata, "EARLY")
